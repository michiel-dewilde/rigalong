#!/usr/bin/env python3
"""gen_cp88x9 -- the CP-88's .X9* file tables and test fixtures, from cp-liveset.

cp-liveset (github.com/michiel-dewilde/cp-liveset) reverse-engineered how a
Live Set Sound sits in the YSFC ".X9*" files the CP88/CP73 reads and writes:
a 367-byte record whose bytes map onto the 17 SysEx data blocks the app
already stores a sound as (model/Cp88.kt). This writes that mapping as
Kotlin tables, so the app reads and writes the files without a port of
cp-liveset's whole parameter model, and fixtures built by cp-liveset itself
from its synthetic sample sounds, which the Kotlin tests must match byte for
byte.

    python tools/gen_cp88x9.py [path/to/cp-liveset]     (default: ../cp-liveset)

Needs cp-liveset importable (pip install -e ../cp-liveset).
"""
import gzip
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
LIVESET = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(APP), "cp-liveset")
sys.path.insert(0, os.path.join(LIVESET, "src"))
sys.path.insert(0, os.path.join(LIVESET, "tests"))

from cp_liveset import codec, paramap, x9data, x9format  # noqa: E402
from _samples import make_sound  # noqa: E402

BLOCKS = [(key, bytes(addr), size) for key, addr, size, _fields in paramap.DATA_BLOCKS]
INDEX = {key: i for i, (key, _a, _s) in enumerate(BLOCKS)}


def off(block, field):
    return x9format._field_offset(block, field)


def stored(sound):
    """A sound in the app's stored form (Cp88.normalize): header, the 17 blocks in order, footer, at 7F 00."""
    blocks = codec.sound_to_blocks(sound)

    def dump(address, data):
        count = len(data) + 4
        total = 0x08 + sum(address) + sum(data)
        return (bytes([0xF0, 0x43, 0x00, 0x7F, 0x1C, (count >> 7) & 0x7F, count & 0x7F, 0x08]) + bytes(address)
                + bytes(data) + bytes([(-total) & 0x7F, 0xF7]))

    out = dump([0x0E, 0x7F, 0x00], b"")
    for key, addr, _size in BLOCKS:
        out += dump(list(addr), bytes(blocks[key]))
    return out + dump([0x0F, 0x7F, 0x00], b"")


def ints(rows):
    flat = [str(v) for row in rows for v in row]
    lines, line = [], "        "
    for v in flat:
        if len(line) + len(v) + 2 > 110:
            lines.append(line.rstrip())
            line = "        "
        line += v + ", "
    lines.append(line.rstrip())
    return "\n".join(lines)


def hexlines(b, width=96):
    h = b.hex()
    return "\n".join(f'        "{h[i:i + width]}" +' for i in range(0, len(h), width)).rstrip(" +")


def kotlin():
    fields = [(INDEX[b], off(b, f) + sub, pos) for b, f, sub, pos in x9data.FIELD_POSITIONS]
    bits = [(INDEX[b], off(b, f) + sub, bit, pos) for b, f, sub, bit, pos in x9data.BIT_POSITIONS]
    repack = [(INDEX[b], off(b, f), lo, hi) for b, f, lo, hi in x9data.REPACK_POSITIONS]
    fixed = [(INDEX[b], off(b, f), v) for b, f, v in x9data.FIXED_VERSION_FIELDS]
    name_block, name_off = INDEX["common"], off("common", "name")
    return f'''package be.mdw.bagosynths.model

// GENERATED by tools/gen_cp88x9.py from cp-liveset's x9data.py and paramap.py.
// Do not edit: run the generator again.

/** Where a Live Set Sound's 17 SysEx data blocks sit in an .X9* file's 367-byte record (Cp88X9). */
internal object Cp88X9Tables {{
    const val BLOB_SIZE = {x9data.BLOB_SIZE}

    /** The data blocks in stored order: three address bytes, then the size. */
    val BLOCKS = intArrayOf(
{ints([(a[0], a[1], a[2], s) for _k, a, s in BLOCKS])}
    )

    /** Block, byte in block, record position: one record byte each. */
    val FIELDS = intArrayOf(
{ints(fields)}
    )

    /** Block, byte in block, bit, record position: a byte stored one bit per record byte. */
    val BITS = intArrayOf(
{ints(bits)}
    )

    /** Block, byte in block, low, high: two 7-bit bytes stored as one 16-bit little-endian value. */
    val REPACK = intArrayOf(
{ints(repack)}
    )

    /** Block, byte in block, value: format stamps the record does not carry. */
    val FIXED = intArrayOf(
{ints(fixed)}
    )

    /** The name: 15 bytes of block {name_block} from byte {name_off}, at record position 4. */
    const val NAME_BLOCK = {name_block}
    const val NAME_OFFSET = {name_off}

    /** The record every written one starts from (its structure bytes). */
    val BASELINE: ByteArray by lazy {{ hex(
{hexlines(x9data.BASELINE_BLOB)}
    ) }}

    /** cp-liveset's Init Sound in the stored form: what an unused slot of a written page holds. */
    val INIT_SOUND: ByteArray by lazy {{ hex(
{hexlines(stored(codec.init_sound()))}
    ) }}

    private fun hex(s: String) = ByteArray(s.length / 2) {{ s.substring(2 * it, 2 * it + 2).toInt(16).toByte() }}
}}
'''


def main():
    out = os.path.join(APP, "model/src/main/kotlin/be/mdw/bagosynths/model/Cp88X9Tables.kt")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(kotlin())
    fx = os.path.join(APP, "model/src/test/resources/cp88")
    os.makedirs(fx, exist_ok=True)
    samples = {(p, s): make_sound(p, s) for p in (3, 7) for s in range(1, 9)}
    # The stored form of each sample, as Cp88.normalize keeps it.
    with open(os.path.join(fx, "samples.syx.hex"), "w", newline="\n") as f:
        for (p, s), sound in sorted(samples.items()):
            f.write(f"{p} {s} {stored(sound).hex()}\n")
    with open(os.path.join(fx, "sample-3-5.X9S"), "wb") as f:
        f.write(x9format.build_x9s(3, 5, samples[(3, 5)]))
    # A page with three sets given; the rest Init Sound.
    page = {(7, s): samples[(7, s)] for s in (1, 2, 6)}
    with open(os.path.join(fx, "sample-page-7.X9P"), "wb") as f:
        f.write(x9format.build_x9p(page, 7, codec.init_sound()))
    # A whole "Live Set All", with its second (init) layer, to read.
    with gzip.GzipFile(os.path.join(fx, "sample-all.X9L.gz"), "wb", mtime=0) as f:
        f.write(x9format.build_x9l(samples, codec.init_sound()))
    print("wrote", out, "and fixtures in", fx)


if __name__ == "__main__":
    main()
