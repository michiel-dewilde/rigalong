#!/usr/bin/env python3
"""gen_cp88x9 -- the CP-88's .X9* file tables and test fixtures, from cp-liveset.

cp-liveset (github.com/michiel-dewilde/cp-liveset) reverse-engineered how a
Live Set Sound sits in the YSFC ".X9*" files the CP88/CP73 reads and writes:
a 367-byte record whose bytes map onto the 17 SysEx data blocks the app
already stores a sound as (model/Cp88.kt). This writes that mapping as
Kotlin tables, so the app reads and writes the files without a port of
cp-liveset's whole parameter model, and fixtures built by cp-liveset itself
from its synthetic sample sounds, which the Kotlin tests must match byte for
byte. Also the tables of its concise YAML form (Cp88YamlTables.kt) and YAML
fixtures: what cp-liveset writes for its samples, names needing every kind of
quoting and random sounds, and what it reads from hand-written YAML; and the
same for its full JSON form.

    python tools/gen_cp88x9.py [path/to/cp-liveset]     (default: ../cp-liveset)

Needs cp-liveset importable (pip install -e ../cp-liveset).
"""
import gzip
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
LIVESET = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(APP), "cp-liveset")
sys.path.insert(0, os.path.join(LIVESET, "src"))
sys.path.insert(0, os.path.join(LIVESET, "tests"))

from cp_liveset import codec, paramap, x9data, x9format, yamldata, yamlformat  # noqa: E402
from _samples import make_sound  # noqa: E402

BLOCKS = [(key, bytes(addr), size) for key, addr, size, _fields in paramap.DATA_BLOCKS]
INDEX = {key: i for i, (key, _a, _s) in enumerate(BLOCKS)}


def off(block, field):
    return x9format._field_offset(block, field)


def stored(sound):
    """A sound in the app's stored form (Cp88.normalize): header, the 17 blocks in order, footer, at 7F 00."""
    blocks = codec.sound_to_blocks(sound)

    def dump(address, data):
        count = len(data) + 4
        total = 0x08 + sum(address) + sum(data)
        return (bytes([0xF0, 0x43, 0x00, 0x7F, 0x1C, (count >> 7) & 0x7F, count & 0x7F, 0x08]) + bytes(address)
                + bytes(data) + bytes([(-total) & 0x7F, 0xF7]))

    out = dump([0x0E, 0x7F, 0x00], b"")
    for key, addr, _size in BLOCKS:
        out += dump(list(addr), bytes(blocks[key]))
    return out + dump([0x0F, 0x7F, 0x00], b"")


def ints(rows):
    flat = [str(v) for row in rows for v in row]
    lines, line = [], "        "
    for v in flat:
        if len(line) + len(v) + 2 > 110:
            lines.append(line.rstrip())
            line = "        "
        line += v + ", "
    lines.append(line.rstrip())
    return "\n".join(lines)


def hexlines(b, width=96):
    h = b.hex()
    return "\n".join(f'        "{h[i:i + width]}" +' for i in range(0, len(h), width)).rstrip(" +")


def kotlin():
    fields = [(INDEX[b], off(b, f) + sub, pos) for b, f, sub, pos in x9data.FIELD_POSITIONS]
    bits = [(INDEX[b], off(b, f) + sub, bit, pos) for b, f, sub, bit, pos in x9data.BIT_POSITIONS]
    repack = [(INDEX[b], off(b, f), lo, hi) for b, f, lo, hi in x9data.REPACK_POSITIONS]
    fixed = [(INDEX[b], off(b, f), v) for b, f, v in x9data.FIXED_VERSION_FIELDS]
    name_block, name_off = INDEX["common"], off("common", "name")
    return f'''package com.rigalong.model.devices.cp88

// GENERATED by tools/gen_cp88x9.py from cp-liveset's x9data.py and paramap.py.
// Do not edit: run the generator again.

/** Where a Live Set Sound's 17 SysEx data blocks sit in an .X9* file's 367-byte record (Cp88X9). */
internal object Cp88X9Tables {{
    const val BLOB_SIZE = {x9data.BLOB_SIZE}

    /** The data blocks in stored order: three address bytes, then the size. */
    val BLOCKS = intArrayOf(
{ints([(a[0], a[1], a[2], s) for _k, a, s in BLOCKS])}
    )

    /** Block, byte in block, record position: one record byte each. */
    val FIELDS = intArrayOf(
{ints(fields)}
    )

    /** Block, byte in block, bit, record position: a byte stored one bit per record byte. */
    val BITS = intArrayOf(
{ints(bits)}
    )

    /** Block, byte in block, low, high: two 7-bit bytes stored as one 16-bit little-endian value. */
    val REPACK = intArrayOf(
{ints(repack)}
    )

    /** Block, byte in block, value: format stamps the record does not carry. */
    val FIXED = intArrayOf(
{ints(fixed)}
    )

    /** The name: 15 bytes of block {name_block} from byte {name_off}, at record position 4. */
    const val NAME_BLOCK = {name_block}
    const val NAME_OFFSET = {name_off}

    /** The record every written one starts from (its structure bytes). */
    val BASELINE: ByteArray by lazy {{ hex(
{hexlines(x9data.BASELINE_BLOB)}
    ) }}

    /** cp-liveset's Init Sound in the stored form: what an unused slot of a written page holds. */
    val INIT_SOUND: ByteArray by lazy {{ hex(
{hexlines(stored(codec.init_sound()))}
    ) }}

    private fun hex(s: String) = ByteArray(s.length / 2) {{ s.substring(2 * it, 2 * it + 2).toInt(16).toByte() }}
}}
'''


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def kmap(table, indent="        "):
    rows = [f"{k} to {kstr(v)}" for k, v in table.items()]
    lines, line = [], indent
    for r in rows:
        if len(line) + len(r) + 2 > 110:
            lines.append(line.rstrip())
            line = indent
        line += r + ", "
    lines.append(line.rstrip())
    return "\n".join(lines)


def yaml_kotlin():
    """The tables of cp-liveset's YAML form (yamldata.py, paramap.py)."""
    keys = [k for k, _a, _s in BLOCKS]
    fields = {k: f for k, _a, _s, f in paramap.DATA_BLOCKS}
    defaults = {k: v for k, v in yamldata.FIELD_DEFAULTS.items() if isinstance(v, int)}
    tempo = yamldata.FIELD_DEFAULTS["additional.tempo_raw"]
    assert [k for k, v in yamldata.FIELD_DEFAULTS.items() if not isinstance(v, int)] == ["additional.tempo_raw"]
    # The raw map lists leftovers in the model's field order: check it is paramap's.
    for key, model in codec._BLOCK_MODELS.items():
        assert list(model.model_fields) == [n for _o, n, _s, _k in fields[key]], key
    block_fields = ",\n".join(
        "        arrayOf(\n" + ints([[f"{kstr(n)} to {o}"] for o, n, _s, _kind in fields[k]]).replace("\n", "\n    ")
        .replace("        ", "            ", 1) + "\n        )"
        for k in keys)
    sizes = {k: {n: s for _o, n, s, _kind in fields[k]} for k in keys}
    assert all(s == 1 for k in keys for n, s in sizes[k].items() if n not in ("name", "tempo_raw"))
    cats = ",\n".join(
        f"        {kstr(sec)} to listOf(\n" + ",\n".join(
            f"            {kstr(c)} to listOf(" + ", ".join(kstr(v) for v in voices) + ")"
            for c, voices in yamldata.SECTION_CATEGORIES[sec]) + ")"
        for sec in paramap.SECTION_NAMES)
    enums = "\n".join(
        f"    val {name} = mapOf(\n{kmap(getattr(yamldata, name))}\n    )\n"
        for name in ("CC_NAMES", "DEPTH_KNOB_SECTION", "DELAY_TYPE", "SPLIT_MODE", "MONO_POLY",
                     "PORTAMENTO_MODE", "PORTAMENTO_TIME_MODE", "PIANO_EFFECT_TYPE", "EPIANO_EFFECT1_TYPE",
                     "EPIANO_EFFECT2_TYPE", "SUB_EFFECT_TYPE", "TEMPO_DELAY_TIME", "EQ_FREQ3", "ADVANCED_VOICES"))
    default_rows = [f"{kstr(k)} to {v}" for k, v in defaults.items()]
    return f'''package com.rigalong.model.devices.cp88

// GENERATED by tools/gen_cp88x9.py from cp-liveset's yamldata.py and paramap.py.
// Do not edit: run the generator again.

/** The tables of cp-liveset's YAML form of a Live Set Sound (Cp88Yaml). */
internal object Cp88YamlTables {{
    /** The data block keys in stored order (Cp88X9Tables.BLOCKS). */
    val BLOCK_KEYS = arrayOf({", ".join(kstr(k) for k in keys)})

    /** Per block, in stored order: every field (reserved bytes named reserved_0xNN) and its offset.
     *  "name" is 15 bytes and "tempo_raw" 2; every other field is one byte. */
    val FIELDS: Array<Array<Pair<String, Int>>> = arrayOf(
{block_fields}
    )

    /** The "standard" value of each one-byte field ("block.field"); a field not listed defaults to 0. */
    val DEFAULTS: Map<String, Int> = hashMapOf(
{ints([[r] for r in default_rows])}
    )

    /** additional.tempo_raw's standard value, [msb, lsb]. */
    val DEFAULT_TEMPO = intArrayOf({tempo[0]}, {tempo[1]})

    /** Per section: its four categories, as the panel names them, with their voices in number order. */
    val SECTION_CATEGORIES: Map<String, List<Pair<String, List<String>>>> = mapOf(
{cats}
    )

{enums}}}
'''


TRICKY_NAMES = [
    "Test 3-5", "", "123", "1.5", "true", "False", "null", "~", "- x", "-x", "a: b", "a:b", "a #b", "a#b",
    "#x", " x", "x'y", 'x"y', "'q'", "@x", "%x", "!x", "*x", "&x", "?x", "? x", "x?", "[x", "x]", "{x", "x,y",
    "0x1F", "1e3", ".5", "Yes", "On", "TRUE", "0o7", "1_0", ".inf", ".NaN", "=", "<<", "x\x7f", "2024-01-01",
    "---x", "...", ":x", ": x", "|x", ">x", "`x", "x\\y", "x  y", "-", "+1", "-.5", "0b101", "-_", "x:",
]


def yaml_text(node):
    buf = io.StringIO()
    yamlformat.make_yaml().dump(node, buf)
    return buf.getvalue()


def yaml_fixtures(fx):
    """yaml-write.txt.gz: stored sound, then cp-liveset's YAML of it (one sound, at column 0).
    yaml-read.txt: hand-written YAML, then the sound cp-liveset reads from it (or ERROR).
    yaml-doc.yaml: a whole document of the samples, as cp-liveset writes it."""
    import random
    from cp_liveset import LiveSetCollection
    rnd = random.Random(88)
    init = codec._init_block_data()
    sounds = [codec.init_sound()] + [make_sound(p, s) for p in (3, 7) for s in range(1, 9)]
    for i, name in enumerate(TRICKY_NAMES):
        for pad in (b"\x00", b" "):
            blocks = dict(init)
            raw = name.encode("ascii").ljust(15, pad)
            blocks["common"] = raw + init["common"][15:]
            sounds.append(codec.sound_from_blocks(blocks))
    sounds.append(codec.sound_from_blocks({**init, "common": b"AB " + b"\x00" * 12 + init["common"][15:]}))
    sounds.append(codec.sound_from_blocks({**init, "common": b" " * 15 + init["common"][15:]}))
    for n in range(200):
        p = (0.03, 0.15, 0.5, 1.0)[n % 4]
        blocks = {}
        for key, _addr, size, fields in paramap.DATA_BLOCKS:
            buf = bytearray(init[key])
            for offset, fname, fsize, kind in fields:
                if kind == "ascii" or rnd.random() >= p:
                    continue
                if key == "additional" and fname == "tempo_raw" and rnd.random() < 0.5:
                    v = rnd.randint(420, 2400)          # a BPM the YAML shows as a number
                    buf[offset:offset + 2] = bytes([v // 128, v % 128])
                    continue
                for o in range(offset, offset + fsize):
                    # half the time a small value, so names and in-range voices come up often
                    buf[o] = rnd.randint(0, 3) if rnd.random() < 0.5 else rnd.randint(0, 127)
            blocks[key] = bytes(buf)
        name = "".join(chr(rnd.randint(0x20, 0x7F)) for _ in range(rnd.randint(0, 15)))
        blocks["common"] = name.encode("ascii").ljust(15, rnd.choice([b"\x00", b" "])) + blocks["common"][15:]
        sounds.append(codec.sound_from_blocks(blocks))
    counts = {}
    with gzip.GzipFile(os.path.join(fx, "yaml-write.txt.gz"), "wb", mtime=0) as gz, \
            io.TextIOWrapper(gz, encoding="utf-8", newline="\n") as f:
        for sound in sounds:
            text = yaml_text(yamlformat.sound_to_yaml(sound))
            try:
                back = yamlformat.sound_from_yaml(yamlformat.make_yaml().load(text))
                how = "exact" if back == sound else "lossy " + stored(back).hex()
            except Exception as e:  # noqa: BLE001 -- cp-liveset refuses some of its own output
                how = "unreadable " + type(e).__name__
            counts[how.split()[0]] = counts.get(how.split()[0], 0) + 1
            f.write(f"=== {stored(sound).hex()} {how}\n{text}")
    print(len(sounds), "YAML write cases; read back by cp-liveset:", counts)
    reads = [
        "name: Plain\n",
        "name: 42\npiano:\n  on: yes\n",
        "name: Organ  # a comment\nsub:\n  on: true\n  category: Organ\n  instrument: Click Organ\n"
        "  effect: {on: true, type: Rotary, speed: 90}\n",
        "name: 'Q''s'\nepiano:\n  on: true\n  category: DX\n  instrument: 4\n  split_mode: 2\n  octave_shift: -1\n",
        'name: "Tab\\0"\npiano:\n  on: true\n  category: Advanced Mode\n  instrument: Imperial+\n',
        "name: Adv\npiano:\n  on: true\n  category: Advanced Mode\n  instrument: 58\n",
        "name: Map\npiano:\n  on: true\n  category: CP\n  instrument:\n    CP: CP80 2\n    Grand Piano: C7\n"
        "    Advanced Mode: 12\n",
        "name: Tempo\ncommon:\n  delay:\n    on: true\n    type: Tempo\n    tempo: 120.5\n    tempo_delay_time: 1/8 Dot.\n"
        "  reverb:\n    on: false\n",
        "name: TempoRaw\ncommon:\n  delay:\n    tempo: [1, 2]\n",
        "name: Notes\ncommon:\n  split_point: C#3\n  modulation_lever:\n    assign: 'P: Tone'\n  fc1:\n    assign: 11\n"
        "zones:\n  2:\n    on: true\n    transmit_channel: 16\n    note_limit: {low: 21, high: G8}\n"
        "    transmit:\n      note: false\n      sustain: false\n",
        "name: EQ\nmaster_eq:\n  on: true\n  low: -12\n  mid_freq: 1.0kHz\n  high: 6\n",
        "name: Raw\nraw:\n  section_piano_common.reserved_0x0e: 5\n  zone_3.reserved_0x06: 1\n"
        "  soundmondo.soundmondo_format_version_minor: 3\n",
        "name: Touch\npiano:\n  on: true\n  touch_sensitivity:\n    depth: 80\n    offset: 70\n"
        "  pitch_modulation_speed: 12\n",
        "name: Bad\npiano:\n  category: Harp\n",
        "name: Bad\nepiano:\n  effect1:\n    type: Fuzz\n",
        "name: This name is far too long\n",
        "name: Bad\npiano:\n  volume: 300\n",
    ]
    with open(os.path.join(fx, "yaml-read.txt"), "w", encoding="utf-8", newline="\n") as f:
        for text in reads:
            try:
                got = stored(yamlformat.sound_from_yaml(yamlformat.make_yaml().load(text))).hex()
            except Exception as e:  # noqa: BLE001 -- any refusal counts
                got = "ERROR " + type(e).__name__
            f.write(f"--- {got}\n{text}")
    group = LiveSetCollection({(p, s): make_sound(p, s) for p in (3, 7) for s in (1, 4, 8)})
    group[(1, 1)] = codec.init_sound()
    with open(os.path.join(fx, "yaml-doc.yaml"), "w", encoding="utf-8", newline="\n") as f:
        f.write(yaml_text(group.to_yaml()))
    return sounds


def json_fixtures(fx, sounds):
    """json-write.txt.gz: stored sound, then cp-liveset's JSON document of it alone, at a page:set that varies.
    json-doc.json: a whole document over several pages, as `cp-liveset convert -o x.json` writes it.
    json-read.txt: hand-written documents, then what cp-liveset reads from them ("p:s=stored ..." or ERROR)."""
    import copy
    import json
    from cp_liveset import LiveSetCollection

    def text(group):
        return json.dumps(group.to_json(), indent=2) + "\n"

    with gzip.GzipFile(os.path.join(fx, "json-write.txt.gz"), "wb", mtime=0) as gz, \
            io.TextIOWrapper(gz, encoding="utf-8", newline="\n") as f:
        for i, sound in enumerate(sounds):
            page, set_no = 1 + i % 40, 1 + i % 8
            f.write(f"=== {page} {set_no} {stored(sound).hex()}\n{text(LiveSetCollection({(page, set_no): sound}))}")
    group = LiveSetCollection({(p, s): make_sound(p, s) for p in (3, 7) for s in (1, 4, 8)})
    group[(10, 2)] = codec.init_sound()
    group[(1, 1)] = sounds[-1]
    with open(os.path.join(fx, "json-doc.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(text(group))

    base = LiveSetCollection({(2, 3): make_sound(3, 5)}).to_json()

    def case(change):
        d = copy.deepcopy(base)
        change(d, d["pages"]["2"]["3"])
        return json.dumps(d, indent=1)

    def setv(path, value):
        def change(_d, s):
            node = s
            for k in path[:-1]:
                node = node[k]
            node[path[-1]] = value
        return change

    def drop(path):
        def change(_d, s):
            node = s
            for k in path[:-1]:
                node = node[k]
            del node[path[-1]]
        return change

    def other(change_doc):
        return lambda d, _s: change_doc(d)

    cases = [
        case(lambda d, s: None),
        case(setv(["common", "name"], "Padded\u0000\u0000")),
        case(setv(["common", "name"], "Spaces    ")),
        case(setv(["common", "name"], "x\u007fy")),
        case(setv(["common", "name"], "Q\"s\\q")),
        case(setv(["common", "name"], "")),
        case(setv(["common", "name"], "Sixteen chars!!!")),
        case(setv(["common", "name"], "Café")),
        case(setv(["common", "name"], "Tab\tx")),
        case(setv(["common", "name"], 42)),
        case(setv(["master_eq", "eq_gain1"], 5.0)),
        case(setv(["master_eq", "eq_gain1"], 5.5)),
        case(setv(["master_eq", "eq_gain1"], "5")),
        case(setv(["master_eq", "eq_gain1"], True)),
        case(setv(["master_eq", "eq_gain1"], None)),
        case(setv(["master_eq", "eq_gain1"], 128)),
        case(setv(["master_eq", "eq_gain1"], -1)),
        case(setv(["zones", 2, "zone_switch"], 1)),
        case(setv(["sections", "sub", "specific", "reserved_0x00"], 9)
             if "reserved_0x00" in base["pages"]["2"]["3"]["sections"]["sub"]["specific"] else lambda d, s: None),
        case(setv(["additional", "tempo_raw"], [3, 4])),
        case(setv(["additional", "tempo_raw"], [3, 4, 5])),
        case(setv(["additional", "tempo_raw"], 7)),
        case(drop(["master_eq", "eq_gain1"])),
        case(setv(["master_eq", "extra"], 1)),
        case(setv(["extra"], {})),
        case(drop(["sections", "epiano"])),
        case(lambda d, s: s.__setitem__("zones", s["zones"][:3])),
        case(other(lambda d: d.__setitem__("format", "cp88-cp73-liveset-yaml-v1"))),
        case(other(lambda d: d.__setitem__("pages", {}))),
        case(other(lambda d: d.pop("pages"))),
        case(other(lambda d: d["pages"].__setitem__("41", {"1": d["pages"]["2"]["3"]}))),
        case(other(lambda d: d["pages"].__setitem__("1", {"9": d["pages"]["2"]["3"]}))),
        case(other(lambda d: d["pages"].__setitem__("01", {"1": d["pages"]["2"]["3"]}))),
        case(other(lambda d: d["pages"]["2"].__setitem__("8", copy.deepcopy(d["pages"]["2"]["3"])))),
        case(other(lambda d: d.__setitem__("note", "kept?"))),
    ]
    with open(os.path.join(fx, "json-read.txt"), "w", encoding="utf-8", newline="\n") as f:
        for doc in cases:
            try:
                got = LiveSetCollection.from_json(json.loads(doc))
                out = " ".join(f"{p}:{s}={stored(got[(p, s)]).hex()}" for p, s in got)
            except Exception as e:  # noqa: BLE001 -- any refusal counts
                out = "ERROR " + type(e).__name__
            f.write(f"--- {out}\n{doc}\n")


def main():
    out = os.path.join(APP, "model/src/main/kotlin/com/rigalong/model/devices/cp88/Cp88X9Tables.kt")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(kotlin())
    with open(os.path.join(os.path.dirname(out), "Cp88YamlTables.kt"), "w", encoding="utf-8", newline="\n") as f:
        f.write(yaml_kotlin())
    fx = os.path.join(APP, "model/src/test/resources/cp88")
    json_fixtures(fx, yaml_fixtures(fx))
    os.makedirs(fx, exist_ok=True)
    samples = {(p, s): make_sound(p, s) for p in (3, 7) for s in range(1, 9)}
    # The stored form of each sample, as Cp88.normalize keeps it.
    with open(os.path.join(fx, "samples.syx.hex"), "w", newline="\n") as f:
        for (p, s), sound in sorted(samples.items()):
            f.write(f"{p} {s} {stored(sound).hex()}\n")
    with open(os.path.join(fx, "sample-3-5.X9S"), "wb") as f:
        f.write(x9format.build_x9s(3, 5, samples[(3, 5)]))
    # A page with three sets given; the rest Init Sound.
    page = {(7, s): samples[(7, s)] for s in (1, 2, 6)}
    with open(os.path.join(fx, "sample-page-7.X9P"), "wb") as f:
        f.write(x9format.build_x9p(page, 7, codec.init_sound()))
    # A whole "Live Set All", with its second (init) layer, to read.
    with gzip.GzipFile(os.path.join(fx, "sample-all.X9L.gz"), "wb", mtime=0) as f:
        f.write(x9format.build_x9l(samples, codec.init_sound()))
    print("wrote", out, "and fixtures in", fx)


if __name__ == "__main__":
    main()
